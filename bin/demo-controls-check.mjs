import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeDemoSource } from './demo-control-policy.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const failures = [];
let examples = 0;
for (const [repo, pkg, prefix] of [['cedar-design-web', 'ui', 'c'], ['maple-design-mobile', 'ui', 'mp']]) {
  const base = path.join(root, repo, 'packages', pkg, 'src');
  for (const relative of fs.readdirSync(base, { recursive: true })) {
    if (!relative.endsWith('.vue') || !/(?:^|\/)(?:__demos__|example)\//.test(relative) || /(?:^|\/)api-review[^/]*\.vue$/.test(relative)) continue;
    const file = path.join(base, relative), source = fs.readFileSync(file, 'utf8');
    if (source.includes('Generated by design-ui/')) continue;
    examples++;
    const output = normalizeDemoSource(source, prefix, file).source;
    if (output !== source) failures.push(path.relative(root, file));
  }
}
console.log(JSON.stringify({ examples, failures }, null, 2));
if (failures.length) process.exitCode = 1;
